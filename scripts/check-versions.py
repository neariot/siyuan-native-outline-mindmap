#!/usr/bin/env python3
"""The version fields that must agree, and the release note that must exist for the current one.

★ Why this exists. The release procedure was a rule held in someone's head: bump the version, remember which
files carry it, and write the release note. `AGENTS.md` section 8 is explicit that a rule enforced by
remembering is a rule that gets forgotten, and a version that disagrees with itself is not a cosmetic
problem —— the bazaar reads the Release and the package's own `plugin.json`, so a half-bumped version ships
a plugin that reports a version different from the one it was released as, and nothing goes red.

★ What it checks.

  1. `package.json` and `src/plugin/plugin.json` carry the **same** version. These are the two authored
     sources: the first is the npm package (what `npm run package` reads), the second is what SiYuan itself
     reads out of the installed plugin directory. `package-lock.json` is generated by npm from the first, so
     checking it would test npm, not this repository.
  2. A `docs/RELEASE-<version>.md` exists. The release notes for this project are versioned files, so the
     question "was a note written for what we are about to ship" has an answer that can be checked.

★ What it cannot see: whether the note's content is true, or whether the version was chosen sensibly (a
  patch bump that changes behaviour is a judgement, not a pattern). It also cannot see the **tag** or the
  **Release** —— those are created outside the repository, and `AGENTS.md` section 4 requires the user's
  consent for them anyway, so a gate must not imply it verified them.

★ When the version in `package.json` is ahead of the note, this **fails**: that is the state where a release
  is half-prepared, which is exactly when the check is worth having. It is not a false positive to silence
  by adding an empty file.
"""
from __future__ import annotations

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

VERSION_RE = re.compile(r"^\d+\.\d+\.\d+$")


def read_version(path: pathlib.Path, dotted: str | None = None) -> str:
    """The version at the top level, or at a dotted key path like `packages..version`."""
    data = json.loads(path.read_text(encoding="utf-8"))
    if dotted:
        for key in dotted.split("."):
            if not isinstance(data, dict) or key not in data:
                return ""
            data = data[key]
        return str(data) if not isinstance(data, dict) else ""
    return str(data.get("version", ""))


def main(argv: list[str]) -> int:
    del argv
    problems: list[str] = []

    pkg = ROOT / "package.json"
    plugin = ROOT / "src" / "plugin" / "plugin.json"
    for p in (pkg, plugin):
        if not p.is_file():
            print(f"check-versions: {p.relative_to(ROOT)} is missing —— the check cannot run", file=sys.stderr)
            return 2

    v_pkg = read_version(pkg)
    v_plugin = read_version(plugin)

    for name, v in (("package.json", v_pkg), ("src/plugin/plugin.json", v_plugin)):
        if not VERSION_RE.match(v):
            problems.append(f"{name}: version {v!r} is not `major.minor.patch`")

    if v_pkg != v_plugin:
        problems.append(
            f"package.json says {v_pkg!r} but src/plugin/plugin.json says {v_plugin!r} —— "
            "the version SiYuan reads would differ from the one that was packaged"
        )

    note = ROOT / "docs" / f"RELEASE-{v_pkg}.md"
    note_exists = note.is_file()

    print(f"check-versions: package.json {v_pkg} · src/plugin/plugin.json {v_plugin}")
    print(f"  release note docs/RELEASE-{v_pkg}.md: {'present' if note_exists else 'MISSING'}")

    if not note_exists:
        # ★ Only a problem when the version is the one about to ship. A version ahead of its note is a
        #   half-prepared release; this is the state the check exists for.
        prev = sorted(
            (p.name for p in (ROOT / "docs").glob("RELEASE-*.md")),
            key=lambda n: [int(x) for x in re.findall(r"\d+", n)],
        )
        problems.append(
            f"docs/RELEASE-{v_pkg}.md does not exist, so the release notes for the current version are "
            f"missing. Notes present: {', '.join(prev) or '(none)'}"
        )

    if problems:
        print()
        for p in problems:
            print(f"  ✘ {p}")
        print("\ncheck-versions: the versioned sources disagree, or the current version has no release note.")
        print("★ Not checked here, because it lives outside the repository and needs consent: the git tag")
        print("  and the GitHub Release. A green run means the files agree, not that anything was published.")
        return 1

    print("check-versions: the versioned sources agree and the release note exists")
    print("★ The tag and the Release are not checked —— they are created outside the repository, and")
    print("  `AGENTS.md` section 4 requires explicit consent for them, so this must not imply it verified them.")
    return 0


if __name__ == "__main__":
    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
    try:
        from script_log import track
    except ImportError:
        sys.exit(main(sys.argv[1:]))
    with track("check-versions"):
        sys.exit(main(sys.argv[1:]))
